import 'dart:typed_data';
import 'package:flutter_test/flutter_test.dart';
import 'package:packet_inspector/domain/models/packet_record.dart';
import 'package:packet_inspector/domain/models/custom_protocol_rule.dart';
import 'package:packet_inspector/data/services/parser/pcap_binary_reader.dart';
import 'package:packet_inspector/data/services/parser/packet_dissector.dart';
import 'package:packet_inspector/data/services/parser/demo_pcap_generator.dart';

void main() {
  group('PcapBinaryReader Tests', () {
    test('Parses classic microsecond PCAP generated by DemoPcapGenerator', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      expect(pcapBytes.length, greaterThan(100));

      final format = PcapBinaryReader.detectFormat(pcapBytes);
      expect(format, equals(PcapFormat.classicMicrosecond));

      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);
      expect(rawPackets.length, greaterThanOrEqualTo(18));

      final firstPacket = rawPackets.first;
      expect(firstPacket.packetNo, equals(1));
      expect(firstPacket.linkType, equals(1)); // Ethernet
      expect(firstPacket.capturedLength, greaterThan(0));
      expect(firstPacket.originalLength, equals(firstPacket.capturedLength));
    });

    test('Parses PCAPNG generated by DemoPcapGenerator', () {
      final pcapNgBytes = DemoPcapGenerator.generatePcapNg();
      final format = PcapBinaryReader.detectFormat(pcapNgBytes);
      expect(format, equals(PcapFormat.pcapNg));

      final rawPackets = PcapBinaryReader.parseBytes(pcapNgBytes);
      expect(rawPackets.length, equals(1));
      expect(rawPackets.first.capturedLength, greaterThan(0));
      expect(rawPackets.first.linkType, equals(1));
    });
  });

  group('PacketDissector Protocol & L7 Tests', () {
    test('Dissects ARP packet and marks as LAN noise', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);

      // Packet 1 is ARP Request
      final arpInfo = PacketDissector.dissect(rawPacket: rawPackets[0]);
      expect(arpInfo.detectedProtocol, equals('ARP'));
      expect(arpInfo.isLanNoise, isTrue);
      expect(arpInfo.summary, contains('Who has 192.168.1.1? Tell 192.168.1.50'));
      expect(arpInfo.srcIp, equals('192.168.1.50'));
      expect(arpInfo.dstIp, equals('192.168.1.1'));
    });

    test('Dissects DNS query and response correctly', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);

      // Packet 3 is DNS query
      final dnsQuery = PacketDissector.dissect(rawPacket: rawPackets[2]);
      expect(dnsQuery.detectedProtocol, equals('DNS'));
      expect(dnsQuery.srcPort, equals(54321));
      expect(dnsQuery.dstPort, equals(53));
      expect(dnsQuery.summary, contains('DNS Standard query'));
      expect(dnsQuery.isLanNoise, isFalse);

      // Packet 4 is DNS response
      final dnsResp = PacketDissector.dissect(rawPacket: rawPackets[3]);
      expect(dnsResp.detectedProtocol, equals('DNS'));
      expect(dnsResp.srcPort, equals(53));
      expect(dnsResp.dstPort, equals(54321));
      expect(dnsResp.summary, contains('DNS Standard response'));
    });

    test('Dissects HTTP GET and response', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);

      // Packet 5 is HTTP GET
      final httpGet = PacketDissector.dissect(rawPacket: rawPackets[4]);
      expect(httpGet.detectedProtocol, equals('HTTP'));
      expect(httpGet.srcPort, equals(49152));
      expect(httpGet.dstPort, equals(80));
      expect(httpGet.summary, contains('GET /index.html'));

      // Packet 6 is HTTP response
      final httpResp = PacketDissector.dissect(rawPacket: rawPackets[5]);
      expect(httpResp.detectedProtocol, equals('HTTP'));
      expect(httpResp.summary, contains('HTTP/1.1 200 OK'));
    });

    test('Dissects mDNS and SSDP and tags as LAN noise', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);

      // Packet 7 is mDNS
      final mdns = PacketDissector.dissect(rawPacket: rawPackets[6]);
      expect(mdns.detectedProtocol, equals('mDNS'));
      expect(mdns.isLanNoise, isTrue);

      // Packet 8 is SSDP
      final ssdp = PacketDissector.dissect(rawPacket: rawPackets[7]);
      expect(ssdp.detectedProtocol, equals('SSDP'));
      expect(ssdp.isLanNoise, isTrue);
    });

    test('Canonical 5-tuple flow hash is symmetric', () {
      final hash1 = PacketDissector.computeFlowHash('192.168.1.10', '8.8.8.8', 54321, 53, 17);
      final hash2 = PacketDissector.computeFlowHash('8.8.8.8', '192.168.1.10', 53, 54321, 17);
      expect(hash1, equals(hash2));
    });

    test('Matches Custom Protocol Rule with Magic Bytes and extracts field slices', () {
      final pcapBytes = DemoPcapGenerator.generateClassicPcap();
      final rawPackets = PcapBinaryReader.parseBytes(pcapBytes);

      final customRule = const CustomProtocolRule(
        id: 'acme_proto',
        name: 'ACME Telemetry',
        colorHex: 0xFF9C27B0,
        defaultTriageStatus: TriageStatus.expected,
        ipProtocol: 17, // UDP
        port: 45820,
        portDirection: PortMatchDirection.either,
        magicBytesOffset: 0,
        magicBytesHex: [0x41, 0x43, 0x4D, 0x45], // "ACME"
        fieldSlices: [
          ProtocolFieldSlice(
            name: 'CommandID',
            byteOffset: 4,
            byteLength: 2,
            dataType: FieldDataType.uint16Be,
          ),
          ProtocolFieldSlice(
            name: 'DeviceSerial',
            byteOffset: 6,
            byteLength: 4,
            dataType: FieldDataType.uint32Be,
          ),
          ProtocolFieldSlice(
            name: 'StatusCode',
            byteOffset: 10,
            byteLength: 1,
            dataType: FieldDataType.uint8,
          ),
          ProtocolFieldSlice(
            name: 'Tag',
            byteOffset: 11,
            byteLength: 4,
            dataType: FieldDataType.asciiString,
          ),
        ],
      );

      // The last packet in the demo is the ACME packet
      final lastPacket = rawPackets.last;
      final info = PacketDissector.dissect(
        rawPacket: lastPacket,
        customRules: [customRule],
      );

      expect(info.detectedProtocol, equals('ACME Telemetry'));
      expect(info.customProtocolId, equals('acme_proto'));
      expect(info.customFields['CommandID'], equals(101));
      expect(info.customFields['DeviceSerial'], equals(883719));
      expect(info.customFields['StatusCode'], equals(1));
      expect(info.customFields['Tag'], equals('PROD'));
      expect(info.summary, contains('CommandID=101'));
      expect(info.summary, contains('DeviceSerial=883719'));
    });

    test('Custom rules prioritize magic bytes over generic port catch-all (specificity ordering)', () {
      // Build UDP packet on port 57313 with offset 153 = 0xDD
      final payload = List<int>.filled(200, 0);
      payload[153] = 0xDD; // sACN Per Address Priority magic byte

      // Raw UDP frame: Ethernet (14) + IPv4 (20) + UDP (8) + payload
      final frame = <int>[
        // Ethernet header (14 bytes)
        0x00, 0x11, 0x22, 0x33, 0x44, 0x55,
        0x66, 0x77, 0x88, 0x99, 0xAA, 0xBB,
        0x08, 0x00, // IPv4
        // IPv4 header (20 bytes)
        0x45, 0x00, 0x00, 0x00,
        0x00, 0x01, 0x00, 0x00,
        0x40, 0x11, 0x00, 0x00, // ttl, UDP (17), checksum
        192, 168, 1, 10,
        192, 168, 1, 20,
        // UDP header (8 bytes)
        0xDF, 0xE1, // src port: 57313
        0xDF, 0xE1, // dst port: 57313
        0x00, (8 + payload.length),
        0x00, 0x00,
        ...payload,
      ];

      final rawPacketPriority = RawCapturedPacket(
        packetNo: 1,
        timestampUs: 1000000,
        capturedLength: frame.length,
        originalLength: frame.length,
        linkType: 1,
        fileByteOffset: 0,
        data: Uint8List.fromList(frame),
      );

      final genericRule = const CustomProtocolRule(
        id: 'sacn_generic',
        name: 'sACN',
        colorHex: 0xFF2196F3,
        defaultTriageStatus: TriageStatus.expected,
        ipProtocol: 17,
        port: 57313,
      );

      final specificRule = const CustomProtocolRule(
        id: 'sacn_priority',
        name: 'sACN Per Address Priority',
        colorHex: 0xFF9C27B0,
        defaultTriageStatus: TriageStatus.expected,
        ipProtocol: 17,
        port: 57313,
        magicBytesOffset: 153,
        magicBytesHex: [0xDD],
      );

      // Even if genericRule is listed FIRST in customRules, specificRule should win!
      final dissectedWithSpecific = PacketDissector.dissect(
        rawPacket: rawPacketPriority,
        customRules: [genericRule, specificRule],
      );
      expect(dissectedWithSpecific.detectedProtocol, equals('sACN Per Address Priority'));
      expect(dissectedWithSpecific.customProtocolId, equals('sacn_priority'));

      // If payload does not have 0xDD at 153, it should fall back to generic sACN
      final frameGeneric = List<int>.from(frame);
      frameGeneric[14 + 20 + 8 + 153] = 0x00; // change offset 153
      final rawPacketGeneric = RawCapturedPacket(
        packetNo: 2,
        timestampUs: 1001000,
        capturedLength: frameGeneric.length,
        originalLength: frameGeneric.length,
        linkType: 1,
        fileByteOffset: 0,
        data: Uint8List.fromList(frameGeneric),
      );

      final dissectedGeneric = PacketDissector.dissect(
        rawPacket: rawPacketGeneric,
        customRules: [genericRule, specificRule],
      );
      expect(dissectedGeneric.detectedProtocol, equals('sACN'));
      expect(dissectedGeneric.customProtocolId, equals('sacn_generic'));
    });
  });
}
